#!/usr/bin/env python3
"""Render deploy/car/.env.generated from .env + tuning.toml [platform.$PLATFORM].

Stdlib only (tomllib => python>=3.11). `make config` runs it inside the ROS image (rccar-ros) with
--user <host uid:gid>, --repo-dir and --dialout-gid passed by make (the container's group db differs).
Output keys (compose reads them with --env-file, `${VAR:?msg}` for required ones):
  PLATFORM ESP32_DEVICE ROS_DOMAIN_ID TZ RCCAR_ROS_IMAGE REPO_DIR HOST_UID HOST_GID DIALOUT_GID
Notes: .claude/rules/deploy.md
"""
import argparse
import os
from pathlib import Path
import re
import sys
import tomllib

DEFAULT_IMAGE = 'rccar-ros:local'
DEFAULT_DOMAIN = '0'
DEFAULT_TZ = 'UTC'
KEY_RE = re.compile(r'^[A-Za-z_][A-Za-z0-9_]*$')


class ConfigError(Exception):
    """User-facing configuration problem (message includes the fix)."""


def parse_env(text: str) -> dict:
    """Parse KEY=VALUE lines. '#' starts a comment at line start or after whitespace."""
    out = {}
    for n, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith('#'):
            continue
        if line.startswith('export '):
            line = line[len('export '):].lstrip()
        if '=' not in line:
            raise ConfigError(f'.env line {n}: expected KEY=VALUE, got {raw!r}')
        key, val = line.split('=', 1)
        key = key.strip()
        if not KEY_RE.match(key):
            raise ConfigError(f'.env line {n}: bad key {key!r}')
        val = val.strip()
        if val[:1] in ('"', "'"):
            end = val.find(val[0], 1)
            if end < 0:
                raise ConfigError(f'.env line {n}: unterminated quote')
            val = val[1:end]
        else:
            val = re.split(r'\s+#', val, maxsplit=1)[0].strip()
        out[key] = val
    return out


def platform_table(tuning: dict, name: str) -> dict:
    platforms = tuning.get('platform')
    if not isinstance(platforms, dict) or name not in platforms:
        known = ', '.join(sorted(platforms)) if isinstance(platforms, dict) else 'none'
        raise ConfigError(f'tuning.toml has no [platform.{name}] (PLATFORM in .env); known: {known}')
    return platforms[name]


def render(env: dict, tuning: dict, repo_dir: str, uid: int, gid: int, dialout_gid: int) -> dict:
    """Return the ordered KEY -> value mapping for .env.generated."""
    name = env.get('PLATFORM', '')
    if not name:
        raise ConfigError('PLATFORM is empty in .env (e.g. PLATFORM=pi5)')
    plat = platform_table(tuning, name)
    device = plat.get('esp32_device')
    if not device or not str(device).startswith('/dev/'):
        raise ConfigError(f'tuning.toml [platform.{name}] esp32_device must be a /dev/... path')
    domain = env.get('ROS_DOMAIN_ID', '') or DEFAULT_DOMAIN
    if not (domain.isdigit() and 0 <= int(domain) <= 101):
        raise ConfigError(f'ROS_DOMAIN_ID={domain!r} must be an integer 0..101')
    return {
        'PLATFORM': name,
        'ESP32_DEVICE': str(device),
        'ROS_DOMAIN_ID': domain,
        'TZ': env.get('TZ', '') or DEFAULT_TZ,
        'RCCAR_ROS_IMAGE': env.get('RCCAR_ROS_IMAGE', '') or DEFAULT_IMAGE,
        'REPO_DIR': repo_dir,
        'HOST_UID': str(uid),
        'HOST_GID': str(gid),
        'DIALOUT_GID': str(dialout_gid),
    }


def format_env(values: dict) -> str:
    lines = ['# generated by deploy/render_env.py (make config): do not edit, do not commit']
    for k, v in values.items():
        quoted = f'"{v}"' if re.search(r'[\s#"\'$]', v) else v
        lines.append(f'{k}={quoted}')
    return '\n'.join(lines) + '\n'


def dialout_gid() -> int:
    try:
        import grp
        return grp.getgrnam('dialout').gr_gid
    except (ImportError, KeyError):
        raise ConfigError("group 'dialout' not found: sudo usermod -aG dialout $USER (docs/setup.md)")


def main(argv=None) -> int:
    root = Path(__file__).resolve().parent.parent
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--env', type=Path, default=root / '.env')
    ap.add_argument('--tuning', type=Path, default=root / 'tuning.toml')
    ap.add_argument('--out', type=Path, default=root / 'deploy' / 'car' / '.env.generated')
    ap.add_argument('--repo-dir', default=str(root))
    ap.add_argument('--dialout-gid', type=int, default=None,
                    help='host dialout gid (default: look up group dialout)')
    args = ap.parse_args(argv)
    try:
        if not args.env.is_file():
            raise ConfigError(f'{args.env.name} missing: cp .env.example .env, then fill it in')
        try:
            with open(args.tuning, 'rb') as f:
                tuning = tomllib.load(f)
        except (OSError, tomllib.TOMLDecodeError) as exc:
            raise ConfigError(f'cannot read {args.tuning}: {exc}')
        values = render(parse_env(args.env.read_text()), tuning, args.repo_dir,
                        os.getuid(), os.getgid(),
                        args.dialout_gid if args.dialout_gid is not None else dialout_gid())
    except ConfigError as exc:
        print(f'config: {exc}', file=sys.stderr)
        return 1
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(format_env(values))
    print(f'config: wrote {args.out} (PLATFORM={values["PLATFORM"]}, '
          f'ESP32_DEVICE={values["ESP32_DEVICE"]}, ROS_DOMAIN_ID={values["ROS_DOMAIN_ID"]})')
    return 0


if __name__ == '__main__':
    sys.exit(main())
